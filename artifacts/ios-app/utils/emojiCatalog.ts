export function normalizeEmoji(value: string): string {
  return value.normalize('NFC');
}

export function firstEmoji(text: string): string {
  const trimmed = text.trim();
  if (!trimmed) return '';
  return [...trimmed.normalize('NFC')][0] ?? '';
}

export function searchEmojis(query: string, recent: readonly string[]): string[] {
  const trimmed = query.trim().toLowerCase();
  if (!trimmed) return [];

  const aliasHits = SEARCH_ALIASES[trimmed] ?? [];
  const direct = ALL_EMOJIS.filter((emoji) => emoji.includes(trimmed));
  const recentHits = recent.filter((emoji) => emoji.includes(trimmed));
  const seen = new Set<string>();
  const results: string[] = [];

  for (const emoji of [...recentHits, ...aliasHits, ...direct]) {
    const normalized = normalizeEmoji(emoji);
    if (!normalized || seen.has(normalized)) continue;
    seen.add(normalized);
    results.push(normalized);
  }

  return results;
}

export function emojisForCategory(categoryId: string, recent: readonly string[]): string[] {
  if (categoryId === 'recent') {
    return [...recent];
  }
  const category = EMOJI_CATEGORIES.find((item) => item.id === categoryId);
  return category ? [...category.emojis] : [];
}

export function defaultIconStyleForGroup(name: string): GroupIconStyleColor {
  let hash = 0;
  for (let i = 0; i < name.length; i += 1) {
    hash = (hash * 31 + name.charCodeAt(i)) | 0;
  }
  const index = Math.abs(hash) % GROUP_ICON_STYLE_COLORS.length;
  return GROUP_ICON_STYLE_COLORS[index]!;
}
